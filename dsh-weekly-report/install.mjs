#!/usr/bin/env node
/**
 * 周报工作台 · 一键安装 / 校验 / 回滚
 *
 *   node install.mjs              安装（幂等）
 *   node install.mjs --dry-run    预览改动，不写文件
 *   node install.mjs --verify     校验安装状态
 *   node install.mjs --uninstall 回滚到安装前
 *   node install.mjs --json       机器可读输出
 *
 * 设计要点：
 *   · 不触碰使用者已有的其它插件配置，只改带标记的整段；
 *   · 包从任意目录运行都可以（路径全部由 import.meta.url 推导），因此可整体分发；
 *   · 沿用旧版的包内文件名 service/server.cjs 与端口 8798 —— DSH 侧边栏 iframe
 *     和宿主保活心跳都不用改，装完立刻能看到新面板，无需重启 DSH；
 *   · 邮件默认关闭、不预置任何凭据；API Key 与路径由使用者在面板里提供。
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const PerfDeps = require('./service/perf-deps.cjs');

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PLUGIN_DIR = HERE;
const SERVER = path.join(PLUGIN_DIR, 'service', 'server.cjs');
const ENGINE = path.join(PLUGIN_DIR, 'service', 'engine', 'gen-weekly.mjs');
const PATCH_FILE = path.join(PLUGIN_DIR, 'cordis.patch.yml');

const argv = process.argv.slice(2);
const HAS = (f) => argv.includes(f);
const DRY = HAS('--dry-run');
const VERIFY = HAS('--verify');
const UNINSTALL = HAS('--uninstall');
const AS_JSON = HAS('--json');
const OPEN = HAS('--open');                 // 装完自动打开面板（双击安装器使用）
const RESULT_IDX = argv.indexOf('--result-file');
const RESULT_FILE = RESULT_IDX >= 0 ? argv[RESULT_IDX + 1] : '';  // 给 VBS 读的 ASCII 摘要
const PROFILE_ARG = argv.find((a) => a.startsWith('--profile='));
const PROFILE = PROFILE_ARG ? PROFILE_ARG.split('=')[1] : 'desktop';

const MARK_BEGIN = '# >>> weekly-report-studio (auto-generated by install.mjs, safe to delete) >>>';
const MARK_END = '# <<< weekly-report-studio <<<';

const DSH_HOME = process.env.DSH_HOME || path.join(process.env.USERPROFILE || os.homedir(), '.dsh');
const PROFILE_DIR = process.env.DSH_PROFILE_DIR || path.join(DSH_HOME, 'profiles', PROFILE);
const PROFILE_PKG = path.join(PROFILE_DIR, 'package.json');
const PROFILE_PATCH = path.join(PROFILE_DIR, 'cordis.patch.yml');
const NM_DIR = path.join(PROFILE_DIR, 'node_modules');
const TARGET = path.join(NM_DIR, 'dsh-weekly-report');
const DATA_DIR = process.env.WEEKLY_PANEL_DATA || process.env.WEEKLY_DATA_DIR
  || path.join(process.env.USERPROFILE || os.homedir(), '.dsh', 'weekly-report');
const STATE_FILE = path.join(DATA_DIR, 'install-state.json');
const PORT = Number(process.env.WEEKLY_PANEL_PORT || 8798);
const BUNDLE = 'dsh-weekly-report';

const results = [];
const rec = (name, ok, detail) => {
  results.push({ name, ok, detail });
  if (!AS_JSON) console.log(`  ${ok ? '✓' : '✗'} ${name}${detail ? ` — ${detail}` : ''}`);
};

function stamp() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}${p(d.getMonth() + 1)}${p(d.getDate())}-${p(d.getHours())}${p(d.getMinutes())}${p(d.getSeconds())}`;
}
function backup(file) {
  try {
    if (!fs.existsSync(file)) return null;
    const dst = `${file}.bak-${stamp()}`;
    fs.copyFileSync(file, dst);
    return dst;
  } catch { return null; }
}
function readJson(file) {
  try { return JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '')); }
  catch { return null; }
}
function writeJson(file, obj) {
  backup(file);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(obj, null, 2) + '\n', 'utf8');
}
function nodeExe() {
  const candidates = [
    process.env.WEEKLY_PANEL_NODE,
    process.env.USERPROFILE
      ? path.join(process.env.USERPROFILE, '.dsh', 'dsh-runtimes', 'dsh-primary-runtime', 'dependencies', 'node', 'bin', 'node.exe')
      : '',
  ].filter(Boolean);
  return candidates.find((p) => fs.existsSync(p)) || process.execPath;
}
async function ping(timeout = 1500) {
  try {
    const res = await fetch(`http://127.0.0.1:${PORT}/api/ping`, { signal: AbortSignal.timeout(timeout), cache: 'no-store' });
    return res.ok ? await res.json() : null;
  } catch { return null; }
}
function readState() {
  const s = readJson(STATE_FILE);
  return s && typeof s === 'object' ? s : {};
}
function writeState(patch) {
  fs.mkdirSync(DATA_DIR, { recursive: true });
  const next = { ...readState(), ...patch, updatedAt: new Date().toISOString() };
  fs.writeFileSync(STATE_FILE, JSON.stringify(next, null, 2) + '\n', 'utf8');
  return next;
}

/** 面板服务：已是本版本就复用；是旧版就接管；没有就拉起。 */
async function ensureService() {
  let live = await ping();
  if (live && live.version === '1.0.0') return { ok: true, detail: `已在运行 pid=${live.pid}` };
  if (live) {
    // 旧版面板占用同一端口：停掉再接管，侧边栏 iframe 指向不变
    if (!DRY) {
      try { process.kill(live.pid); } catch { /* 已经退出 */ }
      for (let i = 0; i < 12; i += 1) {
        await new Promise((r) => setTimeout(r, 250));
        if (!(await ping(600))) break;
      }
    }
  }
  if (DRY) return { ok: true, detail: '将自动启动面板服务' };
  const child = spawn(nodeExe(), [SERVER], {
    cwd: path.dirname(SERVER), detached: true, stdio: 'ignore', windowsHide: true,
    env: { ...process.env, WEEKLY_DATA_DIR: DATA_DIR, WEEKLY_PANEL_DATA: DATA_DIR },
  });
  child.unref();
  for (let i = 0; i < 24; i += 1) {
    await new Promise((r) => setTimeout(r, 300));
    live = await ping(800);
    if (live && live.version === '1.0.0') return { ok: true, detail: `已启动 pid=${live.pid}` };
  }
  return { ok: false, detail: '服务未能就绪，重新打开 DSH 后宿主会自动拉起' };
}

/** 把 profile 的 node_modules/dsh-weekly-report 指向本包（保留原链接备份）。 */
function linkPlugin() {
  if (!fs.existsSync(NM_DIR)) {
    if (!DRY) fs.mkdirSync(NM_DIR, { recursive: true });
  }
  let prevTarget = null;
  try { if (isLink(TARGET)) prevTarget = fs.readlinkSync(TARGET); } catch { /* ignore */ }
  const already = (() => {
    try { return path.resolve(fs.realpathSync(TARGET)) === path.resolve(PLUGIN_DIR); } catch { return false; }
  })();
  if (already) return { ok: true, detail: '已指向本插件', prevTarget };

  if (DRY) return { ok: true, detail: `将把 ${TARGET} 指向 ${PLUGIN_DIR}`, prevTarget };

  // 原链接挪到数据目录备份（不放 node_modules，避免被当成另一个包扫描）
  if (fs.existsSync(TARGET) || isLink(TARGET)) {
    const backupDir = path.join(DATA_DIR, 'backups');
    fs.mkdirSync(backupDir, { recursive: true });
    const parked = path.join(backupDir, `dsh-weekly-report-link-${stamp()}`);
    try { fs.renameSync(TARGET, parked); writeState({ parkedLink: parked }); }
    catch (e) { return { ok: false, detail: `无法移动旧链接：${e.message}`, prevTarget }; }
  }
  try {
    fs.symlinkSync(PLUGIN_DIR, TARGET, process.platform === 'win32' ? 'junction' : 'dir');
  } catch {
    // 无权限建链接时退化为复制（同样装完即用）
    try { fs.cpSync(PLUGIN_DIR, TARGET, { recursive: true }); }
    catch (e) { return { ok: false, detail: `无法安装插件目录：${e.message}`, prevTarget }; }
  }
  return { ok: true, detail: `已注册到 ${TARGET}`, prevTarget };
}
function isLink(p) {
  try { return fs.lstatSync(p).isSymbolicLink(); } catch { return false; }
}

function updateProfilePackage() {
  const pkg = readJson(PROFILE_PKG);
  if (!pkg) return { ok: false, detail: `找不到 ${PROFILE_PKG}` };
  const before = { dependency: (pkg.dependencies || {})[BUNDLE], bundles: [...((pkg.dsh?.profile?.bundles) || [])] };
  pkg.dependencies = { ...(pkg.dependencies || {}), [BUNDLE]: `link:${PLUGIN_DIR}` };
  pkg.dsh = pkg.dsh || {};
  pkg.dsh.profile = pkg.dsh.profile || {};
  const bundles = (pkg.dsh.profile.bundles || []).filter((b) => b !== BUNDLE);
  // 插到 siyuan-bridge 之后，保持原有顺序习惯
  const at = bundles.indexOf('dsh-siyuan-bridge');
  bundles.splice(at >= 0 ? at + 1 : bundles.length, 0, BUNDLE);
  pkg.dsh.profile.bundles = bundles;
  if (!DRY) writeJson(PROFILE_PKG, pkg);
  writeStateBefore(before);
  return { ok: true, detail: `dependency=link:${PLUGIN_DIR}` };
}
function writeStateBefore(before) {
  if (DRY) return;
  // 幂等重跑时不能把「安装前的原值」覆盖成新包自己，否则回滚会失效
  const st = readState();
  const patch = { installedFrom: PLUGIN_DIR, profile: PROFILE };
  if (!st.prevDependency && before.dependency !== `link:${PLUGIN_DIR}`) {
    patch.prevDependency = before.dependency ?? null;
  }
  if (!st.prevBundles) patch.prevBundles = before.bundles;
  writeState(patch);
}

function updatePatch() {
  let text = '';
  try { text = fs.readFileSync(PROFILE_PATCH, 'utf8'); } catch { /* 不存在则新建 */ }
  // 已有同 id 的 insert（旧版手写块）就完全不动，避免破坏使用者配置
  const hasInsert = /-\s*insert:\s*\n\s*-\s*id:\s*weekly-report\b/m.test(text)
    || /id:\s*weekly-report\b/.test(text);
  if (hasInsert) return { ok: true, detail: '已有 weekly-report insert，保留原样' };

  const block = [
    '', MARK_BEGIN,
    '- insert:',
    '    - id: weekly-report',
    `      name: '${BUNDLE}'`,
    '      config: {}',
    MARK_END, '',
  ].join('\n');
  if (!DRY) {
    backup(PROFILE_PATCH);
    fs.mkdirSync(path.dirname(PROFILE_PATCH), { recursive: true });
    fs.writeFileSync(PROFILE_PATCH, text.replace(/\s*$/, '') + '\n' + block, 'utf8');
    writeState({ patchAdded: true });
  }
  return { ok: true, detail: '已插入 weekly-report bundle' };
}

/**
 * 兼容转发（免重启的关键）
 *
 * DSH 里已经加载的旧版 Host 半身，内存中的 HERE 指向旧插件目录，每 20 秒仍会
 * spawn <旧目录>/service/server.cjs。而安装器从终端拉起的进程会话结束就被清理，
 * 端口会被旧服务抢回去。
 *
 * 做法：把旧路径的 server.cjs 备份后换成一行转发，DSH 心跳拉起的进程会直接执行
 * 新包的 service/server.cjs。进程归 DSH 进程树所有，稳定常驻；旧插件的引擎、UI、
 * 配置全部不动，卸载时原文件完整恢复。
 */
function bridgeLegacyHost() {
  const st = readState();
  // parkedLink 是被挪走的原始 junction，readlink 得到的才是最可靠的旧目录
  const candidates = [];
  try { if (st.parkedLink) candidates.push(fs.readlinkSync(st.parkedLink)); } catch { /* ignore */ }
  candidates.push(String(st.prevDependency || '').replace(/^link:/, ''));
  const oldDir = candidates.find((d) => d && path.resolve(d) !== path.resolve(PLUGIN_DIR)
    && fs.existsSync(path.join(d, 'service', 'server.cjs')));
  if (!oldDir) return { ok: true, detail: '无旧版宿主需要兼容，跳过' };
  const oldServer = path.join(oldDir, 'service', 'server.cjs');
  // 顺手把回滚记录修正成真实旧值（幂等重跑可能把它写成新包自己）
  if (!DRY && st.prevDependency !== `link:${oldDir}`) writeState({ prevDependency: `link:${oldDir}` });
  // 版本守卫：候选「旧目录」如果已是同版本或更新的 dsh-weekly-report（比如仓库检出与本机
  // 开发目录内容一致），它不是旧版宿主，绝不能把它的 server.cjs 覆盖成转发（会破坏开发副本）。
  const verAt = (dir) => {
    try { const p = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')); return p.name === 'dsh-weekly-report' ? (p.version || '') : null; }
    catch { return null; }
  };
  const cmpVer = (a, b) => String(a).split('.').map(Number).reduce((acc, x, i) => acc || x - (String(b).split('.')[i] | 0), 0);
  const ownVer = verAt(PLUGIN_DIR) || '';
  const oldVer = verAt(oldDir);
  if (oldVer && ownVer && cmpVer(oldVer, ownVer) >= 0) {
    return { ok: true, detail: `候选路径 ${oldDir} 已是 v${oldVer}（非旧版），不转发` };
  }
  let text = '';
  try { text = fs.readFileSync(oldServer, 'utf8'); } catch { /* ignore */ }
  if (text.includes('weekly-report-studio bridge')) return { ok: true, detail: '兼容转发已存在' };
  if (DRY) return { ok: true, detail: `将把 ${oldServer} 备份后改为转发到新包` };

  const backupDir = path.join(DATA_DIR, 'backups');
  fs.mkdirSync(backupDir, { recursive: true });
  const bak = path.join(backupDir, `legacy-server.cjs.bak-${stamp()}`);
  try { fs.copyFileSync(oldServer, bak); }
  catch (e) { return { ok: false, detail: `备份旧 server.cjs 失败：${e.message}` }; }
  const target = path.join(PLUGIN_DIR, 'service', 'server.cjs');
  const shim = [
    '// weekly-report-studio bridge · 由 install.mjs 生成，原文件已备份',
    '// DSH 宿主保活心跳仍拉起这个路径；这里把执行权交给新包的面板服务。',
    '// 进程归 DSH 进程树所有，可稳定常驻；卸载时原 server.cjs 会完整恢复。',
    `require(${JSON.stringify(target)});`, '',
  ].join('\n');
  try { fs.writeFileSync(oldServer, shim, 'utf8'); }
  catch (e) { return { ok: false, detail: `写入兼容转发失败：${e.message}` }; }
  writeState({ bridgedServer: oldServer, bridgedBackup: bak });
  return { ok: true, detail: `已转发 → ${target}` };
}

function restoreLegacyHost() {
  const st = readState();
  if (!st.bridgedServer || !st.bridgedBackup) return { ok: true, detail: '无需恢复' };
  // 转发文件所在目录已经是本包自身（比如仓库检出后来成了安装路径）：这个文件就是
  // 本包的正式 server.cjs，绝不能拿旧版备份去覆盖它。
  if (path.resolve(path.dirname(st.bridgedServer), '..') === path.resolve(PLUGIN_DIR)) {
    return { ok: true, detail: '心跳路径已并入本包，无需恢复' };
  }
  let text = '';
  try { text = fs.readFileSync(st.bridgedServer, 'utf8'); } catch { /* ignore */ }
  if (!text.includes('weekly-report-studio bridge')) return { ok: true, detail: '旧文件已被人工改回' };
  try {
    fs.copyFileSync(st.bridgedBackup, st.bridgedServer);
    return { ok: true, detail: '旧 server.cjs 已恢复' };
  } catch (e) { return { ok: false, detail: e.message }; }
}

/** 使用者明确要求：邮件默认关闭、不预置任何凭据。只在首次安装时设默认值。 */
function ensureNotifyOff() {
  const st = readState();
  // 幂等重跑 / 使用者后来主动开启邮件时，不再覆盖他的选择
  if (st.installedAt) return { ok: true, detail: '保留使用者当前设置（首次安装已默认关闭）' };
  const cfgFile = path.join(DATA_DIR, 'config.json');
  const cfg = readJson(cfgFile);
  if (!cfg) return { ok: true, detail: '尚无配置，首次启动会写空配置（邮件关闭）' };
  if (cfg.notify && cfg.notify.enabled) {
    if (!DRY) { backup(cfgFile); cfg.notify.enabled = false; fs.writeFileSync(cfgFile, JSON.stringify(cfg, null, 2) + '\n', 'utf8'); }
    return { ok: true, detail: '已按约定把邮件通知设为关闭' };
  }
  return { ok: true, detail: '邮件通知已关闭' };
}

/**
 * 绩效表组件：完整安装包自带 node_modules/exceljs，零网络即可用。
 * 精简包才在线补装；补装失败不阻断安装（周报 txt 本身零依赖），但明确提示。
 */
async function ensurePerfComponent() {
  if (DRY) {
    return {
      ok: true, available: PerfDeps.isAvailable(PLUGIN_DIR),
      detail: PerfDeps.isAvailable(PLUGIN_DIR) ? '组件已随包自带，无需联网' : '将自动补装绩效表组件',
    };
  }
  const r = await PerfDeps.ensure(PLUGIN_DIR);
  const detail = r.mode === 'bundled' ? '组件已随包自带（完全离线可用）'
    : r.available ? `已自动补装（${r.mode}）`
      : `可选组件未就绪，不影响周报生成；${r.hint}`;
  return { ok: true, available: r.available, detail };
}

function removeOurPatch() {
  let text = '';
  try { text = fs.readFileSync(PROFILE_PATCH, 'utf8'); } catch { return; }
  const re = new RegExp(`\\n?${escapeRe(MARK_BEGIN)}[\\s\\S]*?${escapeRe(MARK_END)}\\n?`, 'm');
  if (re.test(text)) {
    backup(PROFILE_PATCH);
    fs.writeFileSync(PROFILE_PATCH, text.replace(re, '\n'), 'utf8');
  }
}
function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

async function doInstall() {
  if (!AS_JSON) console.log(`\n周报工作台 v1.0.0 · ${DRY ? '预览安装' : '一键安装'}\n`);
  rec('运行环境', fs.existsSync(SERVER) && fs.existsSync(ENGINE), `Node ${process.version}`);
  if (!fs.existsSync(SERVER) || !fs.existsSync(ENGINE)) {
    rec('安装中止', false, '包不完整，请确认service/server.cjs与引擎存在'); return finish(1);
  }
  rec('DSH profile 目录', fs.existsSync(PROFILE_DIR), PROFILE_DIR);

  const link = linkPlugin();
  rec('插件注册到 profile', link.ok, link.detail);
  const pkg = updateProfilePackage();
  rec('bundle 清单', pkg.ok, pkg.detail);
  const patch = updatePatch();
  rec('cordis.patch.yml', patch.ok, patch.detail);
  const bridge = bridgeLegacyHost();
  rec('旧宿主兼容转发', bridge.ok, bridge.detail);
  const notify = ensureNotifyOff();
  rec('凭据策略', notify.ok, notify.detail);
  const perf = await ensurePerfComponent();
  rec('绩效表组件', perf.ok, perf.detail);
  const svc = await ensureService();
  rec('面板服务自动启动', svc.ok, svc.detail);
  if (!DRY) writeState({ installedAt: new Date().toISOString(), version: '1.0.0' });
  if (!AS_JSON) {
    console.log(`\n  面板地址：http://127.0.0.1:${PORT}/`);
    console.log('  数据目录：' + DATA_DIR);
    console.log('  API Key / 输出目录 / 绩效表模板 → 在「设置」页按需要提供');
    console.log('  回滚：node install.mjs --uninstall\n');
  }
  return finish(results.every((r) => r.ok) ? 0 : 1);
}

async function doVerify() {
  if (!AS_JSON) console.log('\n周报工作台 · 安装校验\n');
  rec('包完整', fs.existsSync(SERVER) && fs.existsSync(ENGINE) && fs.existsSync(PATCH_FILE), PLUGIN_DIR);
  let linked = false;
  try { linked = path.resolve(fs.realpathSync(TARGET)) === path.resolve(PLUGIN_DIR); } catch { /* ignore */ }
  rec('profile 链接指向本包', linked, TARGET);
  const pkg = readJson(PROFILE_PKG);
  const rawDep = (pkg?.dependencies?.[BUNDLE] || '').trim();
  let depOk = false;
  let depDetail = rawDep || '未找到';
  if (rawDep.startsWith('link:')) {
    // 旧形态：本地 link 安装，依赖值为 link:<路径>，解析后须指向本包
    const dep = rawDep.slice('link:'.length);
    try { depOk = path.resolve(dep) === path.resolve(PLUGIN_DIR); } catch { /* ignore */ }
  } else if (rawDep) {
    // 新形态（npm 安装）：依赖为版本范围（如 ^1.2.1），node_modules/<BUNDLE> 物理副本即本包
    try { depOk = path.resolve(fs.realpathSync(path.join(NM_DIR, BUNDLE))) === path.resolve(PLUGIN_DIR); }
    catch { /* 物理副本不存在则视为未就绪 */ }
    depDetail = `${rawDep}（npm 安装）`;
  }
  rec('dependency 已注册', depOk, depDetail);
  rec('dsh.profile.bundles 已注册', Boolean(pkg?.dsh?.profile?.bundles?.includes(BUNDLE)), '');
  const patchText = (() => { try { return fs.readFileSync(PROFILE_PATCH, 'utf8'); } catch { return ''; } })();
  rec('cordis.patch.yml insert', /id:\s*weekly-report\b/.test(patchText), '');
  // 校验的是「安装时的默认策略」：使用者之后主动开启邮件属于正常偏好，不算失败
  const declared = readJson(path.join(PLUGIN_DIR, 'plugin.json'));
  const cfg = readJson(path.join(DATA_DIR, 'config.json'));
  const defaultOff = Boolean(declared?.configuration?.defaults?.notifyEnabled === false);
  rec('默认策略：邮件关闭 / 零凭据', defaultOff,
    cfg ? (cfg.notify && cfg.notify.enabled ? '使用者已主动开启邮件，已尊重该设置' : '当前也是关闭') : '配置尚未生成');
  const perfOk = PerfDeps.isAvailable(PLUGIN_DIR);
  rec('绩效表组件可用', perfOk, perfOk ? '随包自带，无需补装' : '未就绪，可在设置页补装（不影响周报 txt）');
  const st = readState();
  let bridged = true;
  let bridgeNote = st.bridgedServer ? '' : '全新安装，无需兼容';
  if (st.bridgedServer) {
    const bridgePkg = readJson(path.join(path.dirname(st.bridgedServer), '..', 'package.json'));
    const ownVersion = readJson(path.join(PLUGIN_DIR, 'package.json'))?.version || '';
    const cmpVer = (a, b) => String(a).split('.').map(Number).reduce((acc, x, i) => acc || x - (String(b).split('.')[i] | 0), 0);
    let text = '';
    try { text = fs.readFileSync(st.bridgedServer, 'utf8'); } catch { text = ''; }
    if (text.includes('weekly-report-studio bridge')) {
      bridged = true;
      bridgeNote = '心跳路径已转发到新包';
    } else if (bridgePkg && bridgePkg.name === 'dsh-weekly-report'
      && cmpVer(bridgePkg.version || '0.0.0', ownVersion || '0.0.0') >= 0) {
      // 心跳路径本身已是本插件同版或更新（安装路径 == 心跳路径，或仓库检出接管了旧路径）：
      // 免转发即达标，绝不能拿旧版备份去覆盖它。
      bridged = true;
      bridgeNote = `心跳路径已是本插件 v${bridgePkg.version || '?'}，直跑正式 server`;
    } else {
      bridged = false;
    }
  }
  rec('旧宿主兼容转发', bridged, bridgeNote);
  const live = await ping();
  const pkgVersion = readJson(path.join(PLUGIN_DIR, 'package.json'))?.version || '';
  const liveOk = Boolean(live) && (!pkgVersion || live.version === pkgVersion);
  rec('面板服务在线', liveOk, live ? `v${live.version} pid=${live.pid}${liveOk ? '' : `（包版本 ${pkgVersion}）`}` : '未响应');
  return finish(results.every((r) => r.ok) ? 0 : 1);
}

async function doUninstall() {
  if (!AS_JSON) console.log('\n周报工作台 · 回滚\n');
  const st = readState();
  if (DRY) { console.log('  将恢复 profile 链接 / dependency / bundles，并移除自动插入的配置块'); return finish(0); }
  // 1. 恢复 node_modules 链接
  const parked = st.parkedLink;
  if (fs.existsSync(TARGET) || isLink(TARGET)) {
    try {
      if (isLink(TARGET)) fs.unlinkSync(TARGET);
      else fs.rmSync(TARGET, { recursive: true, force: true });
    } catch { /* ignore */ }
  }
  if (parked && fs.existsSync(parked)) {
    try { fs.renameSync(parked, TARGET); rec('恢复原插件链接', true, parked); }
    catch (e) { rec('恢复原插件链接', false, e.message); }
  } else rec('恢复原插件链接', true, '无原链接需恢复');
  // 2. 恢复 package.json
  const pkg = readJson(PROFILE_PKG);
  if (pkg) {
    if (st.prevDependency) pkg.dependencies = { ...(pkg.dependencies || {}), [BUNDLE]: st.prevDependency };
    else if (pkg.dependencies) delete pkg.dependencies[BUNDLE];
    if (Array.isArray(st.prevBundles)) { pkg.dsh = pkg.dsh || {}; pkg.dsh.profile = pkg.dsh.profile || {}; pkg.dsh.profile.bundles = st.prevBundles; }
    writeJson(PROFILE_PKG, pkg);
    rec('恢复 profile package.json', true, '');
  }
  // 3. 只删自己插入的标记块
  if (st.patchAdded) { removeOurPatch(); rec('移除自动插入的 patch 块', true, ''); }
  else rec('移除自动插入的 patch 块', true, '原配置未改动');
  // 4. 恢复旧 server.cjs，让旧插件完全回到原样
  const restored = restoreLegacyHost();
  rec('恢复旧版 server.cjs', restored.ok, restored.detail);
  // 5. 停掉本插件拉起的服务（端口会被 DSH 宿主重新拉起旧版）
  const live = await ping();
  if (live && live.version === '1.0.0') { try { process.kill(live.pid); } catch { /* ignore */ } }
  rec('停止面板服务', true, 'DSH 宿主会按当前配置重新拉起');
  writeState({ uninstalledAt: new Date().toISOString() });
  if (!AS_JSON) console.log('\n  已回滚。使用者数据（' + DATA_DIR + '）完整保留。\n');
  return finish(0);
}

/** 双击安装器读的结果摘要：只用 ASCII，避免 VBS 以系统代码页读 UTF-8 中文时乱码。 */
function writeResultFile(code) {
  if (!RESULT_FILE || VERIFY || UNINSTALL) return;
  try {
    const good = results.filter((r) => r.ok).length;
    // 只写 ASCII：VBS 以系统代码页读取，中文检查项名称会变成乱码
    const lines = [
      `result=${code === 0 ? 'OK' : 'PARTIAL'} checks=${good}/${results.length}`,
      `panel=http://127.0.0.1:${PORT}/`,
      `verify=node install.mjs --verify`,
    ];
    if (code !== 0) lines.push(`failed=${results.filter((r) => !r.ok).length} (run verify for details)`);
    fs.writeFileSync(RESULT_FILE, lines.join('\n') + '\n', 'ascii');
  } catch { /* 摘要写不了不影响安装 */ }
}

/** 装完自动打开默认浏览器（explorer/open/xdg-open，无黑窗口）。 */
function openPanel() {
  const target = `http://127.0.0.1:${PORT}/`;
  const opts = { detached: true, stdio: 'ignore', windowsHide: true };
  try {
    if (process.platform === 'win32') {
      const exe = path.join(process.env.WINDIR || process.env.SystemRoot || 'C:\\Windows', 'explorer.exe');
      if (fs.existsSync(exe)) { spawn(exe, [target], opts).unref(); return; }
    } else if (process.platform === 'darwin') {
      if (fs.existsSync('/usr/bin/open')) { spawn('/usr/bin/open', [target], opts).unref(); return; }
    } else if (fs.existsSync('/usr/bin/xdg-open')) {
      spawn('/usr/bin/xdg-open', [target], opts).unref(); return;
    }
  } catch { /* 打开失败不影响安装结果 */ }
}

function finish(code) {
  if (AS_JSON) console.log(JSON.stringify({ ok: code === 0, mode: VERIFY ? 'verify' : UNINSTALL ? 'uninstall' : DRY ? 'dry-run' : 'install', pluginDir: PLUGIN_DIR, profile: PROFILE, dataDir: DATA_DIR, port: PORT, checks: results }, null, 2));
  writeResultFile(code);
  if (OPEN && code === 0 && !DRY && !VERIFY && !UNINSTALL) openPanel();
  process.exitCode = code;
  return code;
}

if (VERIFY) await doVerify();
else if (UNINSTALL) await doUninstall();
else await doInstall();
