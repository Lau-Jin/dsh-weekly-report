# Create/overwrite the weekly report task, pointing at the plugin's bundled engine.
#
# Since v0.8.0 the task action is `wscript.exe //nologo <data>\run-weekly-hidden.vbs`
# instead of running python.exe directly: a console app started by Task Scheduler
# shows a console window for a moment, which looked like a blue dialog flashing on
# the desktop. WScript.Shell.Run with window style 0 never shows one.
#
# NOTE: keep this file ASCII-only. Windows PowerShell 5.1 decodes .ps1 files without
# a BOM as ANSI, and non-ASCII bytes in comments can swallow the line ending and
# break the next line (it silently produced a corrupted VBS once).
param(
    [Parameter(Mandatory = $true)][string]$Python,
    [Parameter(Mandatory = $true)][string]$Engine,
    [Parameter(Mandatory = $true)][string]$Config,
    [string]$TaskName = '周报自动生成',
    [string]$Day = 'Sunday',
    [string]$Time = '22:00'
)

$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [Text.Encoding]::UTF8

$engineDir = Split-Path $Engine
$argLine = "`"$Engine`" --config `"$Config`" --week current --perf-auto --log"
$command = "`"$Python`" $argLine"

# Data dir = the folder holding config.json; the launcher lives next to the config.
$dataDir = Split-Path -Parent $Config
if (-not (Test-Path $dataDir)) { New-Item -ItemType Directory -Force -Path $dataDir | Out-Null }
$vbs = Join-Path $dataDir 'run-weekly-hidden.vbs'

# VBS is ASCII too; the real command line is kept in a comment line so the panel
# (service/ps/tasks-info.ps1) can tell which command the task actually runs.
$vbsLines = [string[]]@(
    "' Weekly report task launcher: runs the generator with no console window.",
    "' Generated by service/ps/task-install.ps1 -- change the command there, not here.",
    ("' COMMAND: {0}" -f $command),
    'Option Explicit',
    'Dim sh',
    'Set sh = CreateObject("WScript.Shell")',
    ('sh.Run "{0}", 0, True' -f ($command -replace '"', '""'))
)
[System.IO.File]::WriteAllLines($vbs, $vbsLines, [System.Text.Encoding]::Default)

$wscript = Join-Path $env:WINDIR 'System32\wscript.exe'
$launcherArgs = "//nologo `"$vbs`""
$action = New-ScheduledTaskAction -Execute $wscript -Argument $launcherArgs -WorkingDirectory $engineDir
$trigger = New-ScheduledTaskTrigger -Weekly -DaysOfWeek $Day -At $Time
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit ([TimeSpan]::Zero)

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings -Description 'Weekly report generated by the DSH weekly-report plugin (hidden launcher)' -Force | Out-Null

$i = Get-ScheduledTaskInfo -TaskName $TaskName
@{
    ok      = $true
    next    = if ($i.NextRunTime) { $i.NextRunTime.ToString('yyyy-MM-dd HH:mm') } else { '' }
    action  = "$wscript $launcherArgs"
    command = $command
    hidden  = $true
} | ConvertTo-Json -Compress
